/* Optional real-browser verification; PLAYWRIGHT_MODULE points to an installed runtime. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {once} = require('node:events');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const P = require('../js/ai-pipeline');
const temp = fs.mkdtempSync(path.join(os.tmpdir(),'concreto-ui-'));
process.env.DATABASE_PATH = path.join(temp,'test.sqlite'); process.env.PORT='0';
const server = require('../server');
(async () => {
  if(!server.listening) await once(server,'listening');
  const browser = await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || "chrome"});
  try {
    const errors=[];
    for(const [name,width,height] of [['desktop',1440,1000],['mobile',390,844]]){
      const context=await browser.newContext({viewport:{width,height},colorScheme:'light'});
      const page=await context.newPage();
      page.on('pageerror',error => errors.push(error.message));
      await page.request.post('http://127.0.0.1:'+server.address().port+'/api/db/reset');
      await page.goto('http://127.0.0.1:'+server.address().port);
      await page.locator('#sqliteIndicator.pill.ok').waitFor();
      assert.equal(await page.locator('.col[data-stage="decision"]').count(),1);
      const allCards = await page.locator('.card').count();
      await page.locator('#cardFilter').selectOption('errors');
      assert.equal(await page.locator('.card[data-id="RT-115"]').count(),1);
      assert.ok(await page.locator('.card').count() < allCards);
      await page.locator('#cardFilter').selectOption('below');
      assert.equal(await page.locator('.card[data-id="RT-114"]').count(),1);
      assert.equal(await page.locator('.card[data-id="RT-116"]').count(),0);
      await page.locator('#cardFilter').selectOption('late');
      assert.equal(await page.locator('.card[data-id="RT-113"]').count(),1);
      assert.equal(await page.locator('.card[data-id="RT-114"]').count(),0);
      const previousReport = await page.evaluate(() => {
        const card = estado.cards.find(c => c.id === 'RT-119');
        const previous = card.aiAnalysis;
        card.aiAnalysis = {status:'concluido',verdict:'nao_conforme',summary:'Parecer negativo para teste'};
        return previous;
      });
      await page.locator('#cardFilter').selectOption('negative');
      assert.equal(await page.locator('.card').count(),1);
      assert.equal(await page.locator('.card[data-id="RT-119"]').count(),1);
      await page.evaluate(previous => {estado.cards.find(c => c.id === 'RT-119').aiAnalysis=previous;},previousReport);
      await page.locator('#cardFilter').selectOption('all');
      assert.equal(await page.locator('.card').count(),allCards);
      for(const [group,stages] of [['insertion',['entrada','analise','ajuste']],['automation',['decision','ia']],['followup',['notificar','aguardando','relatorio','finalizado']]]){
        const button=page.locator(`[data-board-group="${group}"]`);
        assert.equal(await button.evaluate(el => getComputedStyle(el).textAlign),'center');
        await button.click();
        assert.equal(await button.getAttribute('aria-expanded'),'false');
        for(const stage of stages) assert.equal(await page.locator(`.col[data-stage="${stage}"]`).count(),0);
        assert.equal(await page.locator(`.col[data-stage="${group === 'followup' ? 'entrada' : 'notificar'}"]`).count(),1);
        await button.click();
        assert.equal(await button.getAttribute('aria-expanded'),'true');
        for(const stage of stages) assert.equal(await page.locator(`.col[data-stage="${stage}"]`).count(),1);
      }
      await page.screenshot({path:path.join(temp,name+'-board.png'),fullPage:true});
      await page.locator('#btnConfig').click();
      await page.locator('[data-cfg-tab="decision"]').click();
      assert.equal(await page.locator('#model-model').inputValue(),'microsoft/microsoft-decision-1');
      const initial=JSON.parse(await page.locator('#cfgModelPreview').inputValue());
      await page.locator('[data-model-group="measurements"]').uncheck();
      const changed=JSON.parse(await page.locator('#cfgModelPreview').inputValue());
      assert.ok(initial.state.measurements);assert.equal(changed.state.measurements,undefined);
      await page.locator('#model-criteria\\.conforme').fill('Critério personalizado para este teste.');
      assert.equal(JSON.parse(await page.locator('#cfgModelPreview').inputValue()).questions.conformidade.criteria.conforme,'Critério personalizado para este teste.');
      await page.locator('.m-box').evaluate(el => el.scrollTop=0);
      await page.screenshot({path:path.join(temp,name+'-decision.png'),fullPage:true});
      await page.locator('[data-cfg-tab="ia"]').click();
      await page.locator('#model-temperature').fill('0.7');
      assert.equal(JSON.parse(await page.locator('#cfgModelPreview').inputValue()).temperature,0.7);
      const overflow=await page.locator('.m-box').evaluate(el => el.scrollWidth > el.clientWidth+2);
      assert.equal(overflow,false,name+' settings must not overflow');
      await page.locator('.m-box').evaluate(el => el.scrollTop=0);
      await page.screenshot({path:path.join(temp,name+'-llm.png'),fullPage:true});
      await page.locator('[data-cfg="review"]').click();
      await page.locator('#cfgNote').fill('Verificação dos controles de IA');
      await page.locator('[data-cfg="confirm"]').click();
      await page.locator('[data-cfg="close"]').click();
      await page.route('**/api/decision/analyze', async route => {
        const body=route.request().postDataJSON();
        await route.fulfill({json:{ok:true,decision:{status:'concluido',verdict:'conforme',model:body.config.decision.model,generatedAt:new Date().toISOString(),confidence:0.8,probabilities:{conforme:0.8,atencao:0.15,nao_conforme:0.05},inputKey:P.inputKey(body.card,body.config,'decision')}}});
      });
      await page.route('**/api/ai/analyze',async route => {
        const body=route.request().postDataJSON();
        assert.equal(body.card.decisionAnalysis.verdict,'conforme');
        await route.fulfill({json:{ok:true,analysis:{status:'concluido',verdict:'conforme',summary:'Título resumido do parecer',content:'## Resumo executivo\nOs resultados atendem ao projeto. [CONFORME]\n\n## 5. Sugestão de Texto Técnico para a Notificação ao Cliente\nPrezados, os ensaios da placa atendem aos limites.\nAtenciosamente, equipe técnica.',model:body.config.ai.model,generatedAt:new Date().toISOString(),inputKey:P.inputKey(body.card,body.config,'ai')}}});
      });
      // A legacy card in the LLM stage must classify first on regeneration.
      await page.locator('.card[data-id="RT-114"]').click();
      await page.locator('#dTabs [data-tab="ajuste"]').click();
      assert.equal(await page.locator('#aj-fck').count(),0);
      await page.locator('#dTabs [data-tab="plan1"]').click();
      assert.match(await page.locator('#plan-fck-limits').innerText(),/17,50 MPa/);
      await page.locator('#plan-fck').fill('40');
      const limits = await page.locator('#plan-fck-limits').innerText();
      for(const value of ['20,00 MPa','30,00 MPa','40,00 MPa']) assert.ok(limits.includes(value));
      await page.locator('#plan-fck').fill('35');
      await page.screenshot({path:path.join(temp,name+'-plan1-fck.png'),fullPage:true});
      await page.locator('#dClose').click();
      await page.locator('.card[data-id="RT-117"]').click();
      await page.locator('#dActions [data-act="gen_ia"]').click();
      await page.locator('#dKey').getByText('Notificar cliente',{exact:true}).waitFor();
      await page.locator('#dTabs [data-tab="notif"]').click();
      await page.locator('[data-act="apply_ia_suggestion"]').click();
      assert.match(await page.locator('#mailText').inputValue(),/^Prezados, os ensaios da placa atendem aos limites/);
      assert.doesNotMatch(await page.locator('#mailText').inputValue(),/Os resultados atendem ao projeto/);
      await page.locator('[data-act="apply_ia_report"]').click();
      assert.doesNotMatch(await page.locator('#mailText').inputValue(),/Sugestão de Texto Técnico/);
      assert.equal((await page.locator('#mailText').inputValue()).split('Prezados, os ensaios').length-1,1);
      assert.match(await page.locator('#mailText').inputValue(),/Os resultados atendem ao projeto\./);
      await page.locator('[data-act="apply_ia_suggestion"]').click();
      assert.equal(await page.locator('#mailText').inputValue(),'Prezados, os ensaios da placa atendem aos limites.\nAtenciosamente, equipe técnica.');
      await page.locator('[data-act="apply_ia_report"]').click();
      const mailto = await page.locator('a[href^="mailto:"]').getAttribute('href');
      assert.match(new URL(mailto).searchParams.get('body'),/Os resultados atendem ao projeto\./);
      await page.locator('#dTabs [data-tab="resumo"]').click();
      await page.locator('#dTabs [data-tab="notif"]').click();
      assert.match(await page.locator('#mailText').inputValue(),/Os resultados atendem ao projeto\./);
      const savedNotice = page.waitForResponse(response => response.url().endsWith('/api/save') && response.request().method() === 'POST');
      await page.locator('[data-act="apply_ia_report"]').click();
      assert.equal((await page.locator('#mailText').inputValue()).split('Os resultados atendem ao projeto.').length-1,1);
      assert.equal((await savedNotice).ok(),true);
      const persisted = await page.request.get(new URL('/api/state',page.url()).href);
      assert.equal((await persisted.json()).cards.find(card => card.id === 'RT-117').aiAnalysis.notificationReport,true);
      await page.reload();
      await page.locator('#sqliteIndicator.pill.ok').waitFor();
      await page.locator('.card[data-id="RT-117"]').click();
      await page.locator('#dTabs [data-tab="notif"]').click();
      assert.match(await page.locator('#mailText').inputValue(),/Os resultados atendem ao projeto\./);
      const edited = 'Prezados, texto revisado pela equipe para o cliente.\nAtenciosamente, responsável técnico.';
      const savedEdit = page.waitForResponse(response => response.url().endsWith('/api/save') && response.request().method() === 'POST');
      await page.locator('#mailText').fill(edited);
      assert.equal(new URL(await page.locator('#mailOpen').getAttribute('href')).searchParams.get('body'),edited);
      await page.locator('#dTabs [data-tab="resumo"]').click();
      await page.locator('#dTabs [data-tab="notif"]').click();
      assert.equal(await page.locator('#mailText').inputValue(),edited);
      assert.equal((await savedEdit).ok(),true);
      await page.reload();
      await page.locator('#sqliteIndicator.pill.ok').waitFor();
      await page.locator('.card[data-id="RT-117"]').click();
      await page.locator('#dTabs [data-tab="notif"]').click();
      assert.equal(await page.locator('#mailText').inputValue(),edited);
      await page.locator('#dTabs [data-tab="hist"]').click();
      const history = await page.locator('#dBody').innerText();
      assert.match(history,/de IA de Decisão \/ classificação para IA generativa \(LLM\)/);
      assert.match(history,/de IA generativa \(LLM\) para Notificar cliente/);
      await context.close();
    }
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ok:true,viewports:['desktop','mobile'],screenshots:temp}));
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;}).finally(async () => {
  await new Promise(resolve => server.close(resolve)); require('../db/database').closeDb();
});
