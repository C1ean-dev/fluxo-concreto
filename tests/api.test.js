const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {once} = require('node:events');
const P = require('../js/ai-pipeline');
const temp = fs.mkdtempSync(path.join(os.tmpdir(),'concreto-api-'));
process.env.DATABASE_PATH = path.join(temp,'test.sqlite');
process.env.PORT = '0';
const {DatabaseSync} = require('node:sqlite');
const legacyDb = new DatabaseSync(process.env.DATABASE_PATH);
legacyDb.exec('CREATE TABLE cards (id TEXT PRIMARY KEY, stage TEXT); CREATE TABLE configuracoes (id INTEGER PRIMARY KEY, rev INTEGER, active TEXT);');
legacyDb.close();
const server = require('../server');
const realFetch = global.fetch;
process.env.OPENROUTER_API_KEY = 'test-only';
let calls=[];
global.fetch = async (url, options) => {
  if(!String(url).startsWith('https://openrouter.ai/')) return realFetch(url,options);
  const body=JSON.parse(options.body); calls.push({url,body});
  return {ok:true,json:async () => String(url).endsWith('/decisions')
    ? {answers:{conformidade:{type:'choice',choice:'conforme',confidence:0.9,probabilities:{conforme:0.9,atencao:0.05,nao_conforme:0.05}}}}
    : {model:body.model,choices:[{message:{content:'## Parecer técnico\nOs resultados disponíveis atendem ao projeto. [CONFORME]'}}]}};
};
test('API previews, classification, report and SQLite round trip use the current snapshot',async () => {
  if(!server.listening) await once(server,'listening');
  const base='http://127.0.0.1:'+server.address().port;
  const post=async (route,body) => {const response=await realFetch(base+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});return {status:response.status,...await response.json()};};
  const state=await (await realFetch(base+'/api/state')).json();
  assert.ok(state.cards[0].log.length > 0,'Stored creation history must appear in the card');
  const card=state.cards[0], config={...state.config,ai:P.config('ai',{model:'test/llm',fallbackModels:[]}),decision:P.config('decision')};
  card.cps[0].carga=12.5;
  config.formulas.fci='20';
  const preview=await post('/api/decision/prompt',{cardId:card.id,card,config});
  assert.equal(preview.status,200);assert.equal(calls.length,0);
  assert.equal(preview.request.state.measurements[0].carga,12.5);
  assert.equal(preview.request.state.calculations[0].fci,20);
  const blocked=await post('/api/ai/analyze',{cardId:card.id,card,config});
  assert.equal(blocked.status,409);
  const classified=await post('/api/decision/analyze',{cardId:card.id,card,config});
  card.decisionAnalysis=classified.decision;
  assert.equal(classified.status,200);assert.deepEqual(calls[0].body,preview.request);
  const llmPreview=await post('/api/ai/prompt',{cardId:card.id,card,config});
  const analyzed=await post('/api/ai/analyze',{cardId:card.id,card,config});
  card.aiAnalysis=analyzed.analysis;
  assert.equal(analyzed.status,200);assert.deepEqual(calls[1].body,llmPreview.request);
  assert.equal(calls[0].body.model,'microsoft/microsoft-decision-1');
  assert.equal(llmPreview.request.messages[1].content.includes('DECISÃO / CLASSIFICAÇÃO'),true);
  card.log.push({t:new Date().toISOString(),text:'Movido automaticamente de IA generativa (LLM) para Notificar cliente'});
  card.notifLog = [{t:'2026-10-13T12:01:00.000Z',ages:[3],mode:'manual'}];
  await post('/api/save',{cards:[card],config});
  await post('/api/save',{cards:[card],config});
  const saved=await (await realFetch(base+'/api/state')).json();
  assert.deepEqual(saved.cards.find(c => c.id===card.id).decisionAnalysis,card.decisionAnalysis);
  assert.deepEqual(saved.cards.find(c => c.id===card.id).log,card.log);
  assert.deepEqual(saved.cards.find(c => c.id===card.id).notifLog,card.notifLog);
  await post('/api/save',{cards:[{...card,log:[]}],config});
  const preserved=await (await realFetch(base+'/api/state')).json();
  assert.deepEqual(preserved.cards.find(c=>c.id===card.id).log,card.log,'Saving an older card snapshot must not erase recorded movements');
  assert.deepEqual(saved.config.decision,config.decision);
  assert.equal(saved.config.ai.model,'openrouter/free');
  assert.equal((await realFetch(base+'/.env')).status,403);
  const wrong=await post('/api/decision/prompt',{cardId:'WRONG',card,config});assert.equal(wrong.status,400);
  const missing=await realFetch(base+'/api/route-that-does-not-exist',{method:'POST'});
  assert.equal(missing.status,404);
  assert.match(missing.headers.get('content-type'),/application\/json/);
  assert.equal((await missing.json()).ok,false);
});
test.after(async () => {
  global.fetch=realFetch;
  await new Promise(resolve => server.close(resolve));
  require('../db/database').closeDb();
  const resolved=path.resolve(temp), tmpRoot=path.resolve(os.tmpdir())+path.sep;
  if(resolved.startsWith(tmpRoot) && path.basename(resolved).startsWith('concreto-api-')) fs.rmSync(resolved,{recursive:true,force:true});
});
